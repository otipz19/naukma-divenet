package ua.ukma.divenet.shared.config;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import tools.jackson.databind.SerializationFeature;
import tools.jackson.databind.json.JsonMapper;

/** Compares the generated OpenAPI document with the committed snapshot, or rewrites the snapshot. */
final class ContractSnapshot {

    static final String REGENERATE_COMMAND = "cd backend && ./mvnw test -Dtest=ApiContractTest -Dopenapi.update=true";

    private static final JsonMapper MAPPER =
            JsonMapper.builder().enable(SerializationFeature.INDENT_OUTPUT).build();

    private ContractSnapshot() {}

    /** Sorted keys, pretty-printed, LF line endings and a trailing newline, whatever the library order. */
    static String normalize(String json) {
        Object tree = sortKeys(MAPPER.readValue(json, Object.class));
        return MAPPER.writeValueAsString(tree).replace("\r\n", "\n") + "\n";
    }

    /**
     * Fails when {@code snapshot} differs from {@code generated}. With {@code update}, writes the
     * snapshot instead. Never writes the file otherwise.
     */
    static void verify(String generated, Path snapshot, boolean update) throws IOException {
        String expected = normalize(generated);
        if (update) {
            Files.createDirectories(snapshot.toAbsolutePath().getParent());
            Files.writeString(snapshot, expected, StandardCharsets.UTF_8);
            return;
        }
        String actual = Files.exists(snapshot)
                ? Files.readString(snapshot, StandardCharsets.UTF_8).replace("\r\n", "\n")
                : null;
        if (!expected.equals(actual)) {
            throw new AssertionError(snapshot.normalize() + " is "
                    + (actual == null ? "missing" : "stale")
                    + ": it does not match the API generated by the back-end. Regenerate it with: "
                    + REGENERATE_COMMAND);
        }
    }

    private static Object sortKeys(Object node) {
        if (node instanceof Map<?, ?> map) {
            Map<String, Object> sorted = new TreeMap<>();
            map.forEach((key, value) -> sorted.put(String.valueOf(key), sortKeys(value)));
            return sorted;
        }
        if (node instanceof List<?> list) {
            return list.stream().map(ContractSnapshot::sortKeys).toList();
        }
        return node;
    }
}
